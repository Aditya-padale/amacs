"""AMACS result objects for detailed execution inspection."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, List, Optional

from amacs.agents.base_agent import AgentResult, SubTask
from amacs.communication import LogEntry


@dataclass
class AdaptationEvent:
    """Record of an adaptation action applied during execution."""

    wave_index: int
    action_type: str
    target_agent_id: str
    description: str
    details: dict[str, Any] = field(default_factory=dict)


@dataclass
class AMACSResult:
    """Full execution container exposing agent responses and inter-agent communication."""

    final_output: str
    agent_results: List[AgentResult] = field(default_factory=list)
    communication_log: List[LogEntry] = field(default_factory=list)
    sub_tasks: List[SubTask] = field(default_factory=list)
    execution_plan: Optional[Any] = None
    system_snapshot: Optional[Any] = None
    adaptation_events: List[AdaptationEvent] = field(default_factory=list)

    def __str__(self) -> str:
        return self.final_output

    def print_agent_responses(self) -> None:
        """Print formatted responses generated by all agents."""
        print("\n==================== 🤖 AGENT RESPONSES ====================")
        for res in self.agent_results:
            status = "SUCCESS" if res.success else f"FAILED ({res.error})"
            print(f"Agent: {res.agent_name:<10} | SubTask ID: {res.sub_task_id:<12} | Status: {status}")
            print(f"Latency: {res.latency_seconds:.2f}s | Tokens: {res.token_usage}")
            print("Response Payload:")
            for line in res.content.splitlines():
                print(f"  │ {line}")
            print("-" * 60)
        print("===========================================================\n")

    def print_communication_log(self) -> None:
        """Print formatted inter-agent pub/sub communication log."""
        print("\n================ 💬 INTER-AGENT COMMUNICATION LOG ================")
        for entry in self.communication_log:
            ow = " [OVERWRITTEN]" if entry.overwritten else ""
            val_str = str(entry.value).replace("\n", " ")
            if len(val_str) > 120:
                val_str = val_str[:117] + "..."
            print(f"[{entry.writer:<10}] -> key '{entry.key}'{ow}: {val_str}")
        print("===================================================================\n")
